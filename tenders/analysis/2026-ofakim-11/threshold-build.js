const FONT = 'Arial';
const thin = { style: BorderStyle.SINGLE, size: 4, color: '808080' };
const borders = { top: thin, bottom: thin, left: thin, right: thin };
const p = (text, o = {}) => new Paragraph({
  bidirectional: true,
  alignment: o.align || AlignmentType.RIGHT,
  spacing: { before: o.before ?? 0, after: o.after ?? 50 },
  keepNext: !!o.keepNext,
  children: [new TextRun({ text, font: FONT, size: o.size || 19, bold: !!o.bold, color: o.color, rightToLeft: true })],
});
const h = (text) => p(text, { bold: true, size: 26, color: '1F4E79', before: 220, after: 100, keepNext: true });

const STATUS_FILL = { 'עומדים': 'E2EFDA', 'לא ידוע': 'FFF2CC', 'לא עומדים': 'F8CBAD' };
function table(head, rows, widths, statusCol = -1) {
  const cell = (t, i, fill, bold, color) => new TableCell({
    width: { size: widths[i], type: WidthType.DXA }, borders,
    margins: { top: 50, bottom: 50, left: 90, right: 90 },
    shading: fill ? { type: ShadingType.CLEAR, fill, color: 'auto' } : undefined,
    children: String(t).split('\n').map(x => p(x, { bold, color })),
  });
  return new Table({
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    columnWidths: widths, visuallyRightToLeft: true,
    rows: [
      new TableRow({ tableHeader: true, children: head.map((t, i) => cell(t, i, '1F4E79', true, 'FFFFFF')) }),
      ...rows.map(r => new TableRow({ cantSplit: true, children: r.map((t, i) => {
        const key = i === statusCol ? Object.keys(STATUS_FILL).find(k => String(t).startsWith(k)) : null;
        return cell(t, i, key ? STATUS_FILL[key] : undefined, i === 0 || i === statusCol);
      }) })),
    ],
  });
}

