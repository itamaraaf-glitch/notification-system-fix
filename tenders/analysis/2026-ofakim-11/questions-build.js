const FONT = 'Arial';
const thin = { style: BorderStyle.SINGLE, size: 4, color: '808080' };
const borders = { top: thin, bottom: thin, left: thin, right: thin };

const p = (text, opts = {}) => new Paragraph({
  bidirectional: true,
  alignment: opts.align || AlignmentType.RIGHT,
  spacing: { after: opts.after ?? 60 },
  children: [new TextRun({ text, font: FONT, size: opts.size || 20, bold: !!opts.bold, rightToLeft: true })],
});

const WIDTHS = [700, 2400, 800, 1900, 9038]; // sums to 14838
const cell = (paras, i, header = false) => new TableCell({
  width: { size: WIDTHS[i], type: WidthType.DXA },
  borders,
  margins: { top: 60, bottom: 60, left: 100, right: 100 },
  shading: header ? { type: ShadingType.CLEAR, fill: 'D9E2F3', color: 'auto' } : undefined,
  children: paras,
});
const lines = (s, opts) => s.split('\n').map(t => p(t, opts));

const headerRow = new TableRow({
  tableHeader: true,
  children: ['מס"ד', 'המסמך או הנספח', 'עמוד', 'סעיף רלבנטי', 'נוסח השאלה']
    .map((h, i) => cell([p(h, { bold: true, align: AlignmentType.CENTER })], i, true)),
});

const VA = { verticalAlign: 'top' };
const cellV = (paras, i, rowSpan) => {
  const c = cell(paras, i);
  return rowSpan > 1 ? new TableCell({
    width: { size: WIDTHS[i], type: WidthType.DXA }, borders, rowSpan,
    margins: { top: 60, bottom: 60, left: 100, right: 100 }, children: paras,
  }) : c;
};
const rows = Q.flatMap(([doc, page, clause, text], idx) => {
  const d = doc.split('\n'), pg = page.split('\n'), cl = clause.split('\n');
  let parts;
  if (d.length === 1) parts = [[d[0], pg.join(', '), cl.join(', ')]];
  else {
    if (pg.length !== d.length || cl.length !== d.length) throw new Error('mismatch in question ' + (idx + 1));
    parts = d.map((x, i) => [x, pg[i], cl[i]]);
  }
  const n = parts.length;
  return parts.map(([dd, pp, cc], j) => new TableRow({
    cantSplit: true,
    children: [
      ...(j === 0 ? [cellV([p(String(idx + 1), { align: AlignmentType.CENTER })], 0, n)] : []),
      cell([p(dd)], 1),
      cell([p(pp, { align: AlignmentType.CENTER })], 2),
      cell([p(cc)], 3),
      ...(j === 0 ? [cellV(text.map(t => p(t)), 4, n)] : []),
    ],
  }));
});

