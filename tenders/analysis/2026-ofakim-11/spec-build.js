function table(head, rows, widths, flagCol = -1) {
  const cell = (t, i, fill, bold, color) => new TableCell({
    width: { size: widths[i], type: WidthType.DXA }, borders, margins: { top: 45, bottom: 45, left: 80, right: 80 },
    shading: fill ? { type: ShadingType.CLEAR, fill, color: 'auto' } : undefined,
    children: String(t).split('\n').map(x => p(x, { bold, color })),
  });
  return new Table({
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA }, columnWidths: widths, visuallyRightToLeft: true,
    rows: [
      new TableRow({ tableHeader: true, children: head.map((t, i) => cell(t, i, '1F4E79', true, 'FFFFFF')) }),
      ...rows.map(r => new TableRow({ cantSplit: true, children: r.map((t, i) => {
        const k = i === flagCol ? Object.keys(FILL).find(x => String(t).startsWith(x)) : null;
        return cell(t, i, k ? FILL[k] : undefined, i === 0 || i === flagCol);
      }) })),
    ],
  });
}
