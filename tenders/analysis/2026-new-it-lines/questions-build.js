const FONT = 'Arial';
const thin = { style: BorderStyle.SINGLE, size: 4, color: '808080' };
const borders = { top: thin, bottom: thin, left: thin, right: thin };
const p = (text, opts = {}) => new Paragraph({
  bidirectional: !opts.ltr,
  alignment: opts.align || AlignmentType.RIGHT,
  spacing: { after: opts.after ?? 60 },
  children: [new TextRun({ text, font: FONT, size: opts.size || 20, bold: !!opts.bold, rightToLeft: !opts.ltr })],
});
const WIDTHS = [700, 1100, 2600, 10438]; // sums to 14838
const cell = (paras, i, header = false) => new TableCell({
  width: { size: WIDTHS[i], type: WidthType.DXA },
  borders,
  margins: { top: 60, bottom: 60, left: 100, right: 100 },
  shading: header ? { type: ShadingType.CLEAR, fill: 'D9E2F3', color: 'auto' } : undefined,
  children: paras,
});
const headerRow = new TableRow({
  tableHeader: true,
  children: ['מס"ד', 'מספר עמוד בחוברת המכרז', 'הסעיף בחוברת המכרז', 'פירוט השאלה']
    .map((h, i) => cell([p(h, { bold: true, align: AlignmentType.CENTER })], i, true)),
});
const rows = Q.map(([page, clause, text], idx) => new TableRow({
  cantSplit: true,
  children: [
    cell([p(String(idx + 1), { align: AlignmentType.CENTER })], 0),
    cell([p(page, { align: AlignmentType.CENTER, ltr: true })], 1),
    cell([p(clause)], 2),
    cell(text.map(t => p(t)), 3),
  ],
}));
const ft = (t) => new TextRun({ text: t, font: FONT, size: 16, rightToLeft: true });
const doc = new Document({
  styles: { default: { document: { run: { font: FONT, size: 20 } } } },
  sections: [{
    properties: { page: { size: { width: 11906, height: 16838, orientation: PageOrientation.LANDSCAPE },
      margin: { top: 900, bottom: 900, left: 1000, right: 1000 } } },
    footers: { default: new Footer({ children: [new Paragraph({ alignment: AlignmentType.CENTER, bidirectional: true, children: [
      ft('עמוד '), new TextRun({ children: [PageNumber.CURRENT], font: FONT, size: 16, rightToLeft: true }),
      ft(' מתוך '), new TextRun({ children: [PageNumber.TOTAL_PAGES], font: FONT, size: 16, rightToLeft: true })] })] }) },
    children: [
      p('לכבוד: עיריית ____________', { size: 22 }),
      p("מכרז מס' ______ – קווי תקשורת, ציוד ורישוי Fortinet ומרכזייה בענן", { bold: true, size: 24, align: AlignmentType.CENTER, after: 80 }),
      p('שאלות הבהרה', { bold: true, size: 26, align: AlignmentType.CENTER, after: 160 }),
      p('שם המשתתף: ______________________    איש קשר: ______________________    טלפון: ______________    דוא"ל: ______________________', { after: 200 }),
      new Table({ width: { size: 14838, type: WidthType.DXA }, columnWidths: WIDTHS, visuallyRightToLeft: true, rows: [headerRow, ...rows] }),
      p('', { after: 200 }),
      p('חתימה וחותמת המשתתף: ______________________          תאריך: ______________'),
    ],
  }],
});
Packer.toBuffer(doc).then(b => { fs.writeFileSync(process.argv[2], b); console.log('written', Q.length, 'questions'); });
